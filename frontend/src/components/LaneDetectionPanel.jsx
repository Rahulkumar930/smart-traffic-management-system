import { useMemo, useState } from "react";

const API_BASE = "http://localhost:5000";

export default function LaneDetectionPanel() {
  const [videoPath, setVideoPath] = useState(
    "C:\\Users\\rahul\\new smart traffic project\\ml-model\\videos\\project_video.mp4"
  );

  const [roadName, setRoadName] = useState("Test Road");
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState(null);
  const [error, setError] = useState("");

  // ============================================================
  // PROCESS VIDEO
  // ============================================================
  const processVideo = async () => {
    if (!videoPath.trim()) {
      setError("Please enter a valid video path.");
      return;
    }

    if (!roadName.trim()) {
      setError("Please enter a road name.");
      return;
    }

    setLoading(true);
    setError("");
    setResult(null);

    try {
      const response = await fetch(`${API_BASE}/api/lane/process`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          videoPath: videoPath.trim(),
          roadName: roadName.trim(),
        }),
      });

      const data = await response.json();

      if (!response.ok || !data.success) {
        throw new Error(
          data.message ||
            data.error ||
            "Lane detection failed. Please check the backend."
        );
      }

      setResult(data);
    } catch (err) {
      console.error("Lane detection error:", err);

      setError(
        err.message ||
          "Unable to connect to the Smart Traffic backend."
      );
    } finally {
      setLoading(false);
    }
  };

  // ============================================================
  // EXTRACT RESULT DATA
  // ============================================================

  const analysis = result?.result || {};
  const record = result?.record || {};

  const framesProcessed =
    analysis.framesProcessed ??
    record.framesProcessed ??
    0;

  const totalVideoFrames =
    analysis.totalVideoFrames ??
    record.totalVideoFrames ??
    framesProcessed;

  const averageRegions =
    analysis.averageDetectedRegions ??
    record.averageDetectedRegions ??
    0;

  const maxRegions =
    analysis.maxDetectedRegions ??
    record.detectedRegions ??
    record.maxDetectedRegions ??
    0;

  const maxVehicles =
    analysis.maxVehiclesInFrame ??
    record.maxVehiclesInFrame ??
    record.vehicleCount ??
    0;

  const averageVehicles =
    analysis.averageVehiclesPerFrame ??
    record.averageVehiclesPerFrame ??
    0;

  const averageSpeed =
    analysis.averageSpeed ??
    record.averageSpeed ??
    0;

  const congestionLevel =
    analysis.congestionLevel ??
    record.congestionLevel ??
    "Low";

  const vehicleTypes = {
    cars:
      analysis.vehicleTypes?.cars ??
      record.vehicleTypes?.cars ??
      0,

    motorcycles:
      analysis.vehicleTypes?.motorcycles ??
      record.vehicleTypes?.motorcycles ??
      0,

    buses:
      analysis.vehicleTypes?.buses ??
      record.vehicleTypes?.buses ??
      0,

    trucks:
      analysis.vehicleTypes?.trucks ??
      record.vehicleTypes?.trucks ??
      0,
  };

  // IMPORTANT:
  // vehicleCount was previously showing 0 because it represented
  // maximum vehicles in one frame rather than total YOLO detections.
  //
  // Total vehicle detections = sum of YOLO class detections.
  const totalVehicleDetections = useMemo(() => {
    return (
      Number(vehicleTypes.cars) +
      Number(vehicleTypes.motorcycles) +
      Number(vehicleTypes.buses) +
      Number(vehicleTypes.trucks)
    );
  }, [
    vehicleTypes.cars,
    vehicleTypes.motorcycles,
    vehicleTypes.buses,
    vehicleTypes.trucks,
  ]);

  // ============================================================
  // PROCESSED VIDEO URL
  // ============================================================

  const videoUrl = useMemo(() => {
    let outputVideo =
      analysis.outputVideo ||
      record.outputVideo ||
      result?.outputVideo ||
      "";

    if (!outputVideo) {
      return "";
    }

    // Convert Windows backslashes to normal slashes.
    outputVideo = outputVideo.replace(/\\/g, "/");

    // Extract only the filename.
    const filename = outputVideo.split("/").pop();

    if (!filename) {
      return "";
    }

    // The browser-compatible file generated by FFmpeg is normally
    // named *_web.mp4.
    let webFilename = filename;

    if (!webFilename.toLowerCase().endsWith("_web.mp4")) {
      const dotIndex = webFilename.lastIndexOf(".");

      if (dotIndex !== -1) {
        webFilename =
          webFilename.substring(0, dotIndex) +
          "_web.mp4";
      } else {
        webFilename += "_web.mp4";
      }
    }

    return `${API_BASE}/videos/${encodeURIComponent(webFilename)}`;
  }, [analysis.outputVideo, record.outputVideo, result]);

  // ============================================================
  // CONGESTION STYLE
  // ============================================================

  const congestionClass = String(congestionLevel).toLowerCase();

  const getCongestionStyle = () => {
    if (congestionClass === "severe") {
      return styles.congestionSevere;
    }

    if (congestionClass === "high") {
      return styles.congestionHigh;
    }

    if (congestionClass === "medium") {
      return styles.congestionMedium;
    }

    return styles.congestionLow;
  };

  // ============================================================
  // UI
  // ============================================================

  return (
    <div style={styles.container}>
      {/* HEADER */}
      <div style={styles.header}>
        <div>
          <h1 style={styles.title}>🚗 Lane Detection</h1>

          <p style={styles.subtitle}>
            AI-powered lane and vehicle analysis for smart
            traffic monitoring.
          </p>
        </div>
      </div>

      {/* INPUT PANEL */}
      <div style={styles.inputPanel}>
        <h2 style={styles.sectionTitle}>
          🎥 Video Processing
        </h2>

        <div style={styles.formGrid}>
          <div style={styles.formGroup}>
            <label style={styles.label}>Road Name</label>

            <input
              type="text"
              value={roadName}
              onChange={(e) => setRoadName(e.target.value)}
              placeholder="Enter road name"
              style={styles.input}
              disabled={loading}
            />
          </div>

          <div style={styles.formGroup}>
            <label style={styles.label}>Video Path</label>

            <input
              type="text"
              value={videoPath}
              onChange={(e) => setVideoPath(e.target.value)}
              placeholder="Enter video path"
              style={styles.input}
              disabled={loading}
            />
          </div>
        </div>

        <button
          onClick={processVideo}
          disabled={loading}
          style={{
            ...styles.button,
            ...(loading ? styles.buttonDisabled : {}),
          }}
        >
          {loading
            ? "⏳ Processing Video..."
            : "▶️ Start Lane Detection"}
        </button>

        {loading && (
          <div style={styles.loadingBox}>
            <div style={styles.spinner}></div>

            <div>
              <strong>Processing road video...</strong>

              <p style={styles.loadingText}>
                OpenCV is detecting lane regions and YOLO is
                detecting vehicles. This may take some time.
              </p>
            </div>
          </div>
        )}

        {error && (
          <div style={styles.error}>
            <strong>❌ Detection Error</strong>

            <p style={{ margin: "6px 0 0" }}>{error}</p>
          </div>
        )}
      </div>

      {/* RESULTS */}
      {result && (
        <>
          {/* COMPLETION HEADER */}
          <div style={styles.successHeader}>
            <div>
              <div style={styles.successTitle}>
                ✅ Detection Completed
              </div>

              <div style={styles.roadName}>
                {record.roadName || roadName}
              </div>
            </div>

            <div
              style={{
                ...styles.congestionBadge,
                ...getCongestionStyle(),
              }}
            >
              🚦 {congestionLevel}
            </div>
          </div>

          {/* MAIN STATISTICS */}
          <div style={styles.statsGrid}>
            {/* TOTAL VEHICLE DETECTIONS */}
            <div style={styles.statCard}>
              <div style={styles.statIcon}>🚗</div>

              <div>
                <div style={styles.statLabel}>
                  Vehicle Detections
                </div>

                <div style={styles.statValue}>
                  {totalVehicleDetections}
                </div>

                <div style={styles.statDescription}>
                  YOLO detections
                </div>
              </div>
            </div>

            {/* MAX VEHICLES */}
            <div style={styles.statCard}>
              <div style={styles.statIcon}>🚘</div>

              <div>
                <div style={styles.statLabel}>
                  Max Vehicles
                </div>

                <div style={styles.statValue}>
                  {maxVehicles}
                </div>

                <div style={styles.statDescription}>
                  In one frame
                </div>
              </div>
            </div>

            {/* LANE REGIONS */}
            <div style={styles.statCard}>
              <div style={styles.statIcon}>🛣️</div>

              <div>
                <div style={styles.statLabel}>
                  Lane Regions
                </div>

                <div style={styles.statValue}>
                  {maxRegions}
                </div>

                <div style={styles.statDescription}>
                  Maximum detected
                </div>
              </div>
            </div>

            {/* AVERAGE REGIONS */}
            <div style={styles.statCard}>
              <div style={styles.statIcon}>📊</div>

              <div>
                <div style={styles.statLabel}>
                  Average Regions
                </div>

                <div style={styles.statValue}>
                  {Number(averageRegions).toFixed(2)}
                </div>

                <div style={styles.statDescription}>
                  Per frame
                </div>
              </div>
            </div>

            {/* FRAMES */}
            <div style={styles.statCard}>
              <div style={styles.statIcon}>🎞️</div>

              <div>
                <div style={styles.statLabel}>
                  Frames Processed
                </div>

                <div style={styles.statValue}>
                  {framesProcessed}
                </div>

                <div style={styles.statDescription}>
                  of {totalVideoFrames}
                </div>
              </div>
            </div>

            {/* CONGESTION */}
            <div style={styles.statCard}>
              <div style={styles.statIcon}>🚦</div>

              <div>
                <div style={styles.statLabel}>
                  Congestion
                </div>

                <div style={styles.statValue}>
                  {congestionLevel}
                </div>

                <div style={styles.statDescription}>
                  Current level
                </div>
              </div>
            </div>
          </div>

          {/* PROCESSED VIDEO */}
          <div style={styles.videoPanel}>
            <div style={styles.videoHeader}>
              <div>
                <h2 style={styles.sectionTitle}>
                  🎥 Processed Traffic Video
                </h2>

                <p style={styles.videoSubtitle}>
                  <strong>OpenCV + YOLO</strong>
                </p>
              </div>
            </div>

            {videoUrl ? (
              <div style={styles.videoWrapper}>
                <video
                  key={videoUrl}
                  controls
                  preload="metadata"
                  style={styles.video}
                >
                  <source
                    src={videoUrl}
                    type="video/mp4"
                  />

                  Your browser does not support HTML5 video.
                </video>
              </div>
            ) : (
              <div style={styles.noVideo}>
                ⚠️ Processed video URL is not available.
              </div>
            )}

            <div style={styles.videoInfo}>
              <strong>Processed Video</strong>

              <p>
                The processed video contains OpenCV lane
                regions and YOLO vehicle detections.
              </p>

              {videoUrl && (
                <a
                  href={videoUrl}
                  target="_blank"
                  rel="noreferrer"
                  style={styles.videoLink}
                >
                  Open processed video in new tab ↗
                </a>
              )}
            </div>
          </div>

          {/* DETECTION SUMMARY */}
          <div style={styles.panel}>
            <h2 style={styles.sectionTitle}>
              📋 Detection Summary
            </h2>

            <div style={styles.summaryGrid}>
              <SummaryItem
                icon="🛣️"
                label="Road"
                value={record.roadName || roadName}
              />

              <SummaryItem
                icon="🚗"
                label="Average Vehicles / Frame"
                value={Number(averageVehicles).toFixed(2)}
              />

              <SummaryItem
                icon="🚘"
                label="Maximum Vehicles / Frame"
                value={maxVehicles}
              />

              <SummaryItem
                icon="🛣️"
                label="Maximum Lane Regions"
                value={maxRegions}
              />

              <SummaryItem
                icon="🎞️"
                label="Frames Processed"
                value={`${framesProcessed} / ${totalVideoFrames}`}
              />

              <SummaryItem
                icon="🚦"
                label="Congestion"
                value={congestionLevel}
              />

              <SummaryItem
                icon="📈"
                label="Average Speed"
                value={`${averageSpeed} km/h`}
              />
            </div>

            <div style={styles.infoMessage}>
              ℹ️ Speed estimation requires camera calibration
              and vehicle tracking.
            </div>
          </div>

          {/* VEHICLE DETECTION */}
          <div style={styles.panel}>
            <div style={styles.vehicleHeader}>
              <div>
                <h2 style={styles.sectionTitle}>
                  🚘 Vehicle Detection
                </h2>

                <p style={styles.muted}>
                  YOLO object detection results
                </p>
              </div>

              <div style={styles.totalVehiclesBadge}>
                Total Detections: {totalVehicleDetections}
              </div>
            </div>

            <div style={styles.vehicleGrid}>
              <VehicleCard
                icon="🚗"
                label="Cars"
                value={vehicleTypes.cars}
              />

              <VehicleCard
                icon="🏍️"
                label="Motorcycles"
                value={vehicleTypes.motorcycles}
              />

              <VehicleCard
                icon="🚌"
                label="Buses"
                value={vehicleTypes.buses}
              />

              <VehicleCard
                icon="🚚"
                label="Trucks"
                value={vehicleTypes.trucks}
              />
            </div>
          </div>

          {/* ANALYSIS DETAILS */}
          <div style={styles.panel}>
            <h2 style={styles.sectionTitle}>
              📊 Analysis Details
            </h2>

            <div style={styles.detailsGrid}>
              <DetailRow
                label="Frames Processed"
                value={framesProcessed}
              />

              <DetailRow
                label="Total Video Frames"
                value={totalVideoFrames}
              />

              <DetailRow
                label="Average Lane Regions"
                value={Number(averageRegions).toFixed(2)}
              />

              <DetailRow
                label="Maximum Lane Regions"
                value={maxRegions}
              />

              <DetailRow
                label="Average Vehicles / Frame"
                value={Number(averageVehicles).toFixed(2)}
              />

              <DetailRow
                label="Maximum Vehicles / Frame"
                value={maxVehicles}
              />

              <DetailRow
                label="Total Vehicle Detections"
                value={totalVehicleDetections}
              />

              <DetailRow
                label="Average Speed"
                value={`${averageSpeed} km/h`}
              />

              <DetailRow
                label="Congestion Level"
                value={congestionLevel}
              />
            </div>
          </div>

          {/* SPEED ESTIMATION */}
          <div style={styles.speedPanel}>
            <div style={styles.speedIcon}>📈</div>

            <div>
              <h3 style={styles.speedTitle}>
                Speed Estimation
              </h3>

              <p style={styles.speedValue}>
                Average Speed:{" "}
                <strong>{averageSpeed} km/h</strong>
              </p>

              <p style={styles.speedNote}>
                Speed estimation requires camera calibration
                and vehicle tracking for accurate km/h values.
              </p>
            </div>
          </div>
        </>
      )}
    </div>
  );
}

// ============================================================
// SUMMARY ITEM
// ============================================================

function SummaryItem({ icon, label, value }) {
  return (
    <div style={styles.summaryItem}>
      <div style={styles.summaryIcon}>{icon}</div>

      <div style={styles.summaryContent}>
        <div style={styles.summaryLabel}>{label}</div>

        <div style={styles.summaryValue}>{value}</div>
      </div>
    </div>
  );
}

// ============================================================
// VEHICLE CARD
// ============================================================

function VehicleCard({ icon, label, value }) {
  return (
    <div style={styles.vehicleCard}>
      <div style={styles.vehicleIcon}>{icon}</div>

      <div>
        <div style={styles.vehicleLabel}>{label}</div>

        <div style={styles.vehicleValue}>{value}</div>
      </div>
    </div>
  );
}

// ============================================================
// DETAIL ROW
// ============================================================

function DetailRow({ label, value }) {
  return (
    <div style={styles.detailRow}>
      <span>{label}</span>

      <strong>{value}</strong>
    </div>
  );
}

